/**
 * Deterministic load-test dataset provisioner (Roadmap 12.3, issue #43).
 *
 * This script does NOT reimplement any domain rule. It composes the app's own
 * public module entry points so the load dataset is created exactly the way the
 * running application would create it:
 *
 *   - catalog:      seedAlbumTemplate(wm2026Template)  installs + publishes the
 *                   full Panini World Cup 2026 revision (~994 stickers, 50
 *                   sections) — realistic album/sticker volume.
 *   - accounts:     registerOpenAccount(...) creates the Better Auth user, its
 *                   credential account (Argon2id) and the collector profile in
 *                   one transaction (identical to open self-registration). We
 *                   pass mode "open" explicitly so seeding works regardless of
 *                   the deployment's REGISTRATION_MODE; nothing about the
 *                   production registration policy is changed.
 *   - onboarding:   markCollectorOnboardingComplete(...) mirrors onboarding.
 *   - trading opt-in: setTradingVisibility(...) opts most collectors in so trade
 *                   matching has visible partners (Roadmap 8.6 visibility).
 *   - holdings:     seedExampleHoldings(...) creates one personal collection per
 *                   collector and inserts holdings; quantities are generated by a
 *                   per-collector deterministic PRNG so collectors have DIFFERENT
 *                   missing stickers and duplicates, which is what makes one-way
 *                   and two-way trade matches exist across the population.
 *
 * Output: load-test/data/users.json — the credentials, collection ids and a few
 * section ids the k6 script needs to log in and exercise real endpoints. The
 * file is git-ignored because it contains login credentials.
 *
 * Re-running is safe: existing users are reused and holdings inserts are
 * ON CONFLICT DO NOTHING (see seedExampleHoldings).
 *
 * Usage (against a reachable DATABASE_URL):
 *   LOAD_USERS=50 pnpm exec tsx load-test/seed/seed-load-dataset.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import { wm2026AlbumId, wm2026RevisionId, wm2026Template } from "@/data/wm2026";
import { closeDatabasePool, getPool, query } from "@/infrastructure/database";
import { seedAlbumTemplate } from "@/modules/catalog";
import { markCollectorOnboardingComplete } from "@/modules/collectors";
import { seedExampleHoldings, type ExampleHoldingsDataset } from "@/modules/collections";
import { registerOpenAccount } from "@/modules/identity";
import { setTradingVisibility } from "@/modules/trading";

interface SeededUser {
  email: string;
  password: string;
  collectorId: string;
  collectionId: string;
  visible: boolean;
}

function intEnv(name: string, fallback: number): number {
  const raw = process.env[name];
  if (!raw) return fallback;
  const value = Number.parseInt(raw, 10);
  return Number.isFinite(value) && value > 0 ? value : fallback;
}

function floatEnv(name: string, fallback: number): number {
  const raw = process.env[name];
  if (!raw) return fallback;
  const value = Number.parseFloat(raw);
  return Number.isFinite(value) ? value : fallback;
}

/** Small deterministic PRNG (mulberry32) so a seeded dataset is reproducible. */
function mulberry32(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

async function main(): Promise<void> {
  const pool = getPool();
  const userCount = intEnv("LOAD_USERS", 50);
  const password = process.env.LOAD_PASSWORD ?? "load-test-password-2026";
  const ownProbability = floatEnv("LOAD_OWN_PROBABILITY", 0.72);
  const duplicateProbability = floatEnv("LOAD_DUPLICATE_PROBABILITY", 0.22);
  const visibleShare = floatEnv("LOAD_VISIBLE_SHARE", 0.9);

  console.info(`Seeding load dataset: ${userCount} collectors, own=${ownProbability}, dup=${duplicateProbability}.`);

  // 1) Realistic catalog volume (idempotent).
  const catalog = await seedAlbumTemplate(wm2026Template);
  console.info(
    catalog.created
      ? `Installed ${wm2026Template.album.title}: ${catalog.sections} sections, ${catalog.stickers} stickers.`
      : `${wm2026Template.album.title} already installed; reusing it.`,
  );

  // Sticker codes and a few sections drive the generated holdings and the k6 filters.
  const stickerRows = await query<{ code: string }>(
    `SELECT code FROM album_revision_stickers WHERE revision_id = $1 ORDER BY sort_order`,
    [wm2026RevisionId],
    pool,
  );
  const stickerCodes = stickerRows.rows.map((row) => row.code);
  if (stickerCodes.length === 0) throw new Error("No stickers found for the World Cup 2026 revision.");

  const sectionRows = await query<{ id: string; code: string; name: string }>(
    `SELECT id, code, name FROM album_sections WHERE revision_id = $1 ORDER BY sort_order LIMIT 8`,
    [wm2026RevisionId],
    pool,
  );

  const users: SeededUser[] = [];
  let totalHoldings = 0;
  let totalDuplicates = 0;
  let visibleCount = 0;

  for (let index = 0; index < userCount; index += 1) {
    const email = `loadtest+${index}@stickerfolio.local`;
    const displayName = `Load Collector ${index + 1}`;

    // Reuse an existing account on a re-run; otherwise create it via the real path.
    const existing = await query<{ id: string }>(`SELECT id FROM "user" WHERE email = $1`, [email], pool);
    let userId: string;
    if (existing.rows[0]) {
      userId = existing.rows[0].id;
    } else {
      ({ userId } = await registerOpenAccount({ email, password, displayName }, pool, "open"));
    }

    const collector = await query<{ id: string }>(
      `SELECT id FROM collector_profiles WHERE user_id = $1`,
      [userId],
      pool,
    );
    const collectorId = collector.rows[0]?.id;
    if (!collectorId) throw new Error(`Collector profile missing for ${email}.`);

    await markCollectorOnboardingComplete(collectorId, pool);

    const visible = index / userCount < visibleShare;
    await setTradingVisibility(collectorId, visible, pool);
    if (visible) visibleCount += 1;

    // Per-collector deterministic holdings: differing owned/missing/duplicate
    // patterns are what create real one-way and two-way trade matches.
    const random = mulberry32(1000 + index);
    const quantities: Record<string, number> = {};
    for (const code of stickerCodes) {
      if (random() < ownProbability) {
        const quantity = random() < duplicateProbability ? 2 + Math.floor(random() * 2) : 1;
        quantities[code] = quantity;
        totalHoldings += 1;
        if (quantity > 1) totalDuplicates += 1;
      }
    }

    const dataset: ExampleHoldingsDataset = {
      id: `load:wm2026:${index}`,
      albumId: wm2026AlbumId,
      revisionId: wm2026RevisionId,
      quantities,
    };
    const result = await seedExampleHoldings(collectorId, dataset, pool);

    users.push({ email, password, collectorId, collectionId: result.collectionId, visible });
    if ((index + 1) % 10 === 0 || index + 1 === userCount) {
      console.info(`  provisioned ${index + 1}/${userCount} collectors`);
    }
  }

  const output = {
    generatedAt: new Date().toISOString(),
    baseUrlHint: process.env.APP_BASE_URL ?? "http://localhost:3500",
    authTrustedIpHeader: process.env.AUTH_TRUSTED_IP_HEADER ?? null,
    album: {
      id: wm2026AlbumId,
      revisionId: wm2026RevisionId,
      slug: wm2026Template.album.slug,
      title: wm2026Template.album.title,
      stickerCount: stickerCodes.length,
    },
    stats: {
      users: users.length,
      visibleCollectors: visibleCount,
      totalHoldings,
      totalDuplicates,
    },
    sections: sectionRows.rows,
    users,
  };

  const outPath = path.resolve(process.cwd(), "load-test/data/users.json");
  mkdirSync(path.dirname(outPath), { recursive: true });
  writeFileSync(outPath, `${JSON.stringify(output, null, 2)}\n`, { mode: 0o600 });

  console.info(
    `Done. ${users.length} collectors (${visibleCount} visible), ${totalHoldings} holdings ` +
      `(${totalDuplicates} duplicates). Wrote ${outPath}.`,
  );
}

main()
  .catch((error) => {
    console.error(error instanceof Error ? error.message : "Load dataset seed failed.");
    process.exitCode = 1;
  })
  .finally(() => {
    void closeDatabasePool();
  });
